// Backpressure experiment (Lab 4, M3): download a big match log through a slow channel and
// sample the SERVER process's resident memory (rss).
//
//   node scripts/rss-bench.ts [--mb=200] [--rate=2] [--seconds=30] [--out=../docs/lab-04]
//
// Two server endpoints serve the same file to the same throttled client:
//   /api/replays/:id         pipeline(createReadStream, res) — streams, honours backpressure
//   /api/replays-naive/:id   readFile → res.end(buffer)      — the whole file in memory
// The client reads `--rate` MB/s (default 2 ≈ 16 Mbit/s) by pausing its socket, which makes
// the kernel's receive window fill and the server's res.write() start returning false —
// exactly what a slow mobile connection does. Samples go to <out>/rss.csv.

import { spawn } from "node:child_process";
import { mkdtemp, readFile, rm, stat, writeFile, mkdir } from "node:fs/promises";
import http from "node:http";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs, startServer } from "./common.ts";

const args = parseArgs();
const MB = Number(args.mb ?? 200);
const RATE = Number(args.rate ?? 2) * 1024 * 1024; // bytes per second the client consumes
const SECONDS = Number(args.seconds ?? 30);
const OUT = args.out ?? join(import.meta.dirname, "../../docs/lab-04");
const SAMPLE_MS = 200;

const dir = await mkdtemp(join(tmpdir(), "dogfight-rss-"));
const id = "belt-ab12-1700000000000";
const file = join(dir, `${id}.ndjson`);

// 1. the 200 MB log (generated by the project's own script, itself a stream pipeline)
await new Promise<void>((resolve, reject) => {
  const p = spawn(process.execPath, [join(import.meta.dirname, "make-log.ts"), file, String(MB)], {
    stdio: "inherit",
  });
  p.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`make-log exited ${code}`))));
});
console.log(
  `log: ${((await stat(file)).size / 1048576).toFixed(0)} MB, client rate ${RATE / 1048576} MB/s, ${SECONDS} s per run`,
);

// 2. the real server in a child process, so its rss is its own
const { child: server, base } = await startServer(join(import.meta.dirname, "../src/index.ts"), {
  PORT: "0",
  LOG_DIR: dir,
  CLIENT_DIST: dir,
  ENABLE_DEBUG_ROUTES: "1",
});

const rssMB = async (): Promise<number> => {
  const status = await readFile(`/proc/${server.pid}/status`, "utf8");
  return Number(/VmRSS:\s+(\d+) kB/.exec(status)?.[1]) / 1024;
};

/** Reads `url` at RATE bytes/s for `seconds`, sampling the server's rss; returns the samples. */
interface Sample {
  label: string;
  phase: "idle" | "download" | "after";
  t: number;
  rss: number;
}

async function run(label: string, url: string) {
  const samples: Sample[] = [];
  const t0 = performance.now();
  const sample = async (phase: Sample["phase"]): Promise<void> => {
    samples.push({ label, phase, t: (performance.now() - t0) / 1000, rss: await rssMB() });
  };

  for (let i = 0; i < 10; i++) {
    await sample("idle");
    await new Promise((r) => setTimeout(r, SAMPLE_MS));
  }
  const idleEnd = (performance.now() - t0) / 1000;

  let received = 0;
  let budget = 0;
  const req = http.get(url);
  const res = await new Promise<http.IncomingMessage>((resolve, reject) => {
    req.on("response", resolve);
    req.on("error", reject);
  });
  res.on("error", () => {});
  res.on("data", (chunk: Buffer) => {
    received += chunk.length;
    budget -= chunk.length;
    if (budget <= 0) res.pause();
  });
  const refill = setInterval(() => {
    budget += RATE * (SAMPLE_MS / 1000);
    if (budget > 0) res.resume();
  }, SAMPLE_MS);

  const end = performance.now() + SECONDS * 1000;
  while (performance.now() < end) {
    await sample("download");
    await new Promise((r) => setTimeout(r, SAMPLE_MS));
  }
  clearInterval(refill);
  res.destroy();
  req.destroy();
  await new Promise((r) => setTimeout(r, 500)); // let the server notice the hang-up
  await sample("after");
  return { samples, idleEnd, received };
}

const pipelineRun = await run("pipeline", `${base}/api/replays/${id}`);
await new Promise((r) => setTimeout(r, 1500));
const naiveRun = await run("naive", `${base}/api/replays-naive/${id}`);
const results = { pipeline: pipelineRun, naive: naiveRun };

server.kill("SIGTERM");
await rm(dir, { recursive: true, force: true });

// 3. numbers
const summary: Record<
  string,
  { idleMB: number; peakMB: number; growthMB: number; downloadedMB: number }
> = {};
for (const [name, r] of Object.entries(results)) {
  const idle = r.samples.filter((s) => s.phase === "idle").map((s) => s.rss);
  const dl = r.samples.filter((s) => s.phase === "download").map((s) => s.rss);
  summary[name] = {
    idleMB: Math.round(Math.min(...idle)),
    peakMB: Math.round(Math.max(...dl)),
    growthMB: Math.round(Math.max(...dl) - Math.min(...idle)),
    downloadedMB: Math.round(r.received / 1048576),
  };
}
console.table(summary);

await mkdir(OUT, { recursive: true });
const csv = [
  "run,phase,t_seconds,rss_mb",
  ...Object.values(results).flatMap((r) =>
    r.samples.map((s) => `${s.label},${s.phase},${s.t.toFixed(2)},${s.rss.toFixed(1)}`),
  ),
];
await writeFile(join(OUT, "rss.csv"), `${csv.join("\n")}\n`);
await writeFile(
  join(OUT, "rss-summary.json"),
  `${JSON.stringify({ logMB: MB, rateMBps: RATE / 1048576, seconds: SECONDS, ...summary, idleEndsAt: { pipeline: pipelineRun.idleEnd, naive: naiveRun.idleEnd } }, null, 2)}\n`,
);
console.log(`wrote ${join(OUT, "rss.csv")}`);
